import { readFile } from 'node:fs/promises'
import path from 'node:path'
import { h } from '@purestack/ts-html'
import { withBasePath } from '@purestack/ts-util'
import { definePlugin } from 'purestack'
import {
  dashboardConfigPath,
  dashboardEventPath,
  dashboardTrackerPath,
  defaultConfig,
} from '../content/lib/contracts'
import { defineDashboardComponents } from './components'
import { dashboardSkin } from './skin'
import { registerDashboardStyles } from './styles'

let trackerSourcePath = ''

// Every page is a full load, so the sidebar would start at the top after each click. This runs
// right after the sidebar markup, before the first paint: it restores the position the tab last
// had, or brings the current page's link into view, and saves the position when the page is left.
// The navigation for the remembered role (lib/session.ts) is shown first, so the sidebar already
// has its full height and the position is not cut short when the session confirms the role.
const sidebarScrollScript = `(function () {
  var sidebar = document.querySelector('.sidebar')
  if (!sidebar) return
  var key = 'zt-sidebar-scroll'
  try {
    var role = localStorage.getItem('zt-dashboard-role')
    var root = document.documentElement
    if (role === 'Administrator') root.classList.add('role-admin')
    if (role === 'Administrator' || role === 'Analyst') root.classList.add('role-query')
  } catch (error) {}
  try {
    var saved = sessionStorage.getItem(key)
    if (saved !== null) sidebar.scrollTop = Number(saved)
    else {
      var current = sidebar.querySelector('[aria-current="page"]')
      if (current) current.scrollIntoView({ block: 'nearest' })
    }
  } catch (error) {}
  function save() {
    try {
      sessionStorage.setItem(key, String(sidebar.scrollTop))
    } catch (error) {}
  }
  sidebar.addEventListener('click', save)
  addEventListener('pagehide', save)
  // Escape closes the navigation drawer on narrow screens.
  addEventListener('keydown', function (event) {
    var toggle = document.getElementById('nav-toggle')
    if (event.key === 'Escape' && toggle && toggle.checked) toggle.checked = false
  })
})()`
const previewUser = {
  id: 'preview',
  userName: 'preview',
  displayName: 'Preview administrator',
  role: 'Administrator',
  canQuery: true,
}

// A dedicated application template, following the reference site's plugin model.
// All routes, assets and PageScript bundles are still generated by PureStack.
export const dashboardPlugin = definePlugin({
  name: 'zonetree-dashboard',
  skins: { zonetree: dashboardSkin },
  components: defineDashboardComponents,
  devMiddleware: async (request, response) => {
    const pathname = new URL(request.url ?? '/', 'http://localhost').pathname
    if (pathname === dashboardTrackerPath && request.method === 'GET') {
      const tracker = await readFile(trackerSourcePath)
      response
        .writeHead(200, {
          'Content-Type': 'application/javascript',
          'Cache-Control': 'no-store',
        })
        .end(tracker)
      return
    }
    if (pathname === dashboardEventPath && request.method === 'POST') {
      // Standalone PureStack previews have synthetic reports and no analytics store.
      response.writeHead(204).end()
      return
    }
    // Standalone previews act as a signed-in administrator; the dashboard API needs the server.
    if (pathname === '/_dashboard/api/auth/me' && request.method === 'GET') {
      response
        .writeHead(200, {
          'Content-Type': 'application/json',
          'Cache-Control': 'no-store',
        })
        .end(
          JSON.stringify({
            user: {
              ...previewUser,
              allSites: true,
              sites: [],
              disabled: false,
              created: new Date(0).toISOString(),
              lastSignIn: null,
            },
            sites: defaultConfig.sites,
            sessionId: 'preview',
          }),
        )
      return
    }
    if (pathname.startsWith('/_dashboard/api/')) {
      response.writeHead(404, { 'Content-Type': 'application/json' }).end(
        JSON.stringify({
          error:
            'This needs the ZoneTree Analytics server. The standalone preview has no dashboard API.',
        }),
      )
      return
    }
    if (pathname !== dashboardConfigPath) return
    if (request.method !== 'GET') {
      response.writeHead(405, { Allow: 'GET' }).end()
      return
    }
    response
      .writeHead(200, {
        'Content-Type': 'application/json',
        'Cache-Control': 'no-store',
      })
      .end(
        JSON.stringify({
          ...defaultConfig,
          timeZone: 'UTC',
          user: previewUser,
        }),
      )
  },
  hooks: {
    onConfigResolved: (context) => {
      registerDashboardStyles()
      trackerSourcePath = path.resolve(
        context.config.contentDir,
        '../../../../src/ZoneTree.Analytics.AspNetCore/tracker.js',
      )
    },
    onPageRendered: (context, page) => {
      // The tracker endpoint stays at the host root when static pages use a base path.
      const resolvedPath = withBasePath(
        context.config.basePath,
        dashboardTrackerPath,
      )
      if (resolvedPath !== dashboardTrackerPath) {
        page.html = page.html
          .replace(`src="${resolvedPath}`, `src="${dashboardTrackerPath}`)
          .replace(`src=${resolvedPath}`, `src=${dashboardTrackerPath}`)
      }
    },
  },
  templates: {
    // Sign-in, sign-out and setup: no navigation and no tracker.
    auth: ({ head, bodyHtml, site }) => {
      head.push(
        h('meta').attr({ name: 'robots', content: 'noindex, nofollow' }),
      )
      return h('html')
        .attr({ lang: 'en', 'data-theme': 'light' })
        .push(
          head,
          h('body')
            .class('zt-dashboard zt-auth')
            .attr({ 'data-base-path': site.basePath || '/' })
            .push(
              h('a')
                .class('skip-link')
                .attr({ href: '#main' })
                .text('Skip to content'),
              h('div').class('auth-shell').raw(bodyHtml),
            ),
        )
    },
    dashboard: ({ head, bodyHtml, headerHtml, site, pageInfo }) => {
      head.push(
        h('script').attr({
          id: 'zonetree-tracker',
          defer: '',
          src: `${dashboardTrackerPath}?v=2`,
          'data-allow-localhost': 'true',
          'data-track-navigation': 'false',
        }),
      )
      head.push(
        h('meta').attr({ name: 'robots', content: 'noindex, nofollow' }),
      )
      head.push(
        h('noscript').push(
          h('style').raw(
            'html:not([data-theme-ready]) body{visibility:visible}',
          ),
        ),
      )
      return h('html')
        .attr({ lang: 'en', 'data-theme': 'light' })
        .push(
          head,
          h('body')
            .class('zt-dashboard')
            .attr({
              'data-base-path': site.basePath || '/',
              'data-section': String(
                pageInfo.frontmatter.section ?? 'overview',
              ),
            })
            .push(
              h('a')
                .class('skip-link')
                .attr({ href: '#main' })
                .text('Skip to content'),
              h('input')
                .class('nav-toggle')
                .id('nav-toggle')
                .attr({ type: 'checkbox', 'aria-label': 'Toggle navigation' }),
              h('div')
                .class('app-shell')
                .push(
                  h('').raw(headerHtml ?? ''),
                  h('script').raw(sidebarScrollScript),
                  // Covers the page while the navigation drawer is open: a click on it closes the drawer.
                  h('label')
                    .class('nav-backdrop')
                    .attr({ for: 'nav-toggle', 'aria-hidden': 'true' }),
                  h('div').class('main-shell').raw(bodyHtml),
                ),
            ),
        )
    },
  },
})
